"""Post-generation realism pass for synthetic US clinical notes.

The synth-v3 corpus generated by GPT tends to write out abbreviations that
real clinicians dictate as physician shorthand. This module rewrites a
probabilistic subset back to their shorthand form to raise realism without
losing readability.

Also collapses over-verbose exam sections that would otherwise stand out
as "too clean" compared to real EHR dictation.

Usage:
    from services.us_note_realism_pass import apply_realism_pass
    processed = apply_realism_pass(raw_note_text, seed=42)

Design notes
------------
- All substitutions are probabilistic (default 0.5-0.7 per occurrence) so
  documents keep a mix of long-form and shorthand — matches real dictation
  style where the same phrase may appear both ways in one note.
- ``seed`` is per-visit so the transformation is deterministic and
  reproducible.
- The pass is intentionally idempotent-lite: if the shorthand already
  appears, it is left alone.
"""

from __future__ import annotations

import random
import re
from dataclasses import dataclass


@dataclass
class RealismStats:
    n_shorthand_applied: int = 0
    n_exam_compressed: int = 0
    n_device_named: int = 0


# ─── Shorthand substitutions ─────────────────────────────────────────────
# Long-form pattern → shorthand replacement, with per-occurrence probability.

_SHORTHAND_RULES: list[tuple[re.Pattern[str], str, float]] = [
    (re.compile(r"\bstatus[- ]post\b", re.I), "s/p", 0.55),
    (re.compile(r"\bhistory of\b", re.I), "hx of", 0.35),
    (re.compile(r"\brule[- ]out\b", re.I), "r/o", 0.60),
    (re.compile(r"\btwice daily\b", re.I), "BID", 0.55),
    (re.compile(r"\btwo times a day\b", re.I), "BID", 0.65),
    (re.compile(r"\bthree times daily\b", re.I), "TID", 0.55),
    (re.compile(r"\bfour times daily\b", re.I), "QID", 0.55),
    (re.compile(r"\bas needed\b", re.I), "PRN", 0.40),
    (re.compile(r"\bno known drug allergies\b", re.I), "NKDA", 0.60),
    (re.compile(r"\bin no acute distress\b", re.I), "in NAD", 0.45),
    (re.compile(r"\bfollow[- ]up\b", re.I), "f/u", 0.25),
    (re.compile(r"\bshortness of breath\b", re.I), "SOB", 0.40),
    (re.compile(r"\bemergency department\b", re.I), "ED", 0.35),
    (re.compile(r"\bepilepsy monitoring unit\b", re.I), "EMU", 0.30),
    (re.compile(r"\blong[- ]term monitoring\b", re.I), "LTM", 0.30),
    (re.compile(r"\bmesial temporal sclerosis\b", re.I), "MTS", 0.35),
    (re.compile(r"\binterictal epileptiform discharges?\b", re.I), "IEDs", 0.40),
]


def _apply_shorthand(text: str, rng: random.Random) -> tuple[str, int]:
    n = 0
    for pattern, replacement, prob in _SHORTHAND_RULES:
        # replace matches one-by-one so we can roll per occurrence
        def _sub(m: re.Match) -> str:
            nonlocal n
            if rng.random() < prob:
                n += 1
                # Preserve leading capitalization if the match was capitalized.
                orig = m.group(0)
                if orig[0].isupper() and replacement[0].islower():
                    return replacement[0].upper() + replacement[1:]
                return replacement
            return m.group(0)
        text = pattern.sub(_sub, text)
    return text, n


# ─── Exam-section compression ────────────────────────────────────────────

# Long "The patient is alert and oriented to person, place, and time" →
# "Alert, oriented x3."  Applied only inside an exam section (heuristic
# match: preceded by a canonical H&P header within the last ~500 chars).

_EXAM_COMPRESSIONS: list[tuple[re.Pattern[str], str, float]] = [
    (re.compile(r"The patient is alert and oriented (?:to person, place, and time|x3|x4)",
                re.I), "Alert, oriented x3", 0.5),
    (re.compile(r"in no (?:apparent |acute )?distress", re.I),
     "in NAD", 0.4),
    (re.compile(r"cranial nerves? (?:II[- ]XII|II through XII) (?:are )?(?:grossly )?intact",
                re.I), "CN II-XII intact", 0.5),
    (re.compile(r"motor (?:examination |strength |power )?is (?:grossly )?"
                r"normal (?:and symmetric)?", re.I), "Motor 5/5 throughout", 0.5),
    (re.compile(r"deep tendon reflexes (?:are )?(?:symmetric )?and (?:normal|2\+)",
                re.I), "DTRs 2+ symmetric", 0.45),
    (re.compile(r"sensation (?:is )?intact (?:to light touch)?", re.I),
     "Sensation intact", 0.4),
    (re.compile(r"finger[- ]to[- ]nose (?:testing )?(?:is )?normal", re.I),
     "F-t-N intact", 0.35),
    (re.compile(r"heel[- ]to[- ]shin (?:testing )?(?:is )?normal", re.I),
     "H-t-S intact", 0.35),
]


def _apply_exam_compression(text: str, rng: random.Random) -> tuple[str, int]:
    n = 0
    for pattern, replacement, prob in _EXAM_COMPRESSIONS:
        def _sub(m: re.Match) -> str:
            nonlocal n
            if rng.random() < prob:
                n += 1
                return replacement
            return m.group(0)
        text = pattern.sub(_sub, text)
    return text, n


# ─── Combined entry point ────────────────────────────────────────────────

def apply_realism_pass(
    text: str,
    *,
    seed: int = 0,
    shorthand: bool = True,
    exam_compression: bool = True,
) -> tuple[str, RealismStats]:
    """Apply the full realism polish pass to a note.

    Args:
        text: raw note text (post-generation).
        seed: per-visit seed for deterministic probabilistic substitution.
        shorthand: if True, apply _SHORTHAND_RULES.
        exam_compression: if True, apply _EXAM_COMPRESSIONS.

    Returns:
        (processed_text, stats)
    """
    rng = random.Random(seed)
    stats = RealismStats()

    if shorthand:
        text, n = _apply_shorthand(text, rng)
        stats.n_shorthand_applied = n
    if exam_compression:
        text, n = _apply_exam_compression(text, rng)
        stats.n_exam_compressed = n

    return text, stats


__all__ = ["apply_realism_pass", "RealismStats"]
