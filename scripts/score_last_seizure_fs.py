#!/usr/bin/env python3
"""Rules-only score of ``date_of_last_seizure`` on all 200 F-S letters, development and held-out split.

Gold: YearDate(-MonthDate) of "0 seizures since <date>" SeizureFrequency entities (one per seizure type).  A
letter's predicted date is right if it matches any of them at the gold's precision.  Dates found in letters with
no gold date are listed separately: the F-S annotators mark the date only on zero-seizure entities, so a stated
"last episode was on 31st August 2018" can be a real date the gold does not hold.

    venv-medcat/bin/python scripts/score_last_seizure_fs.py --out eval/results/leo_last_seizure_fs200
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from scripts.score_leo_vs_fs_gold import FS_TEXT_DIR, HELD_OUT, fs_seizure_free_gold  # noqa: E402
from services.seizure_free import date_matches, last_seizure_date  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="eval/results/leo_last_seizure_fs200")
    args = ap.parse_args()
    held = set(HELD_OUT)
    rows, extra = [], []
    agg = {"dev": [0, 0, 0, 0], "held_out": [0, 0, 0, 0]}   # tp, fp, fn, letters with gold
    for i in range(1, 201):
        pid = f"EA{i:04d}"
        text = (FS_TEXT_DIR / f"{pid}.txt").read_text(encoding="utf-8")
        _, gold = fs_seizure_free_gold(pid)
        hit = last_seizure_date(text)
        pred = hit[0] if hit else None
        quote = text[hit[1]:hit[2]].replace("\n", " ") if hit else ""
        split = "held_out" if pid in held else "dev"
        if not gold:
            if pred:
                extra.append({"pid": pid, "split": split, "pred": pred, "quote": quote})
            continue
        ok = pred is not None and any(date_matches(pred, g) for g in gold)
        a = agg[split]
        a[0] += ok
        a[1] += pred is not None and not ok
        a[2] += not ok
        a[3] += 1
        rows.append({"pid": pid, "split": split, "gold": gold, "pred": pred, "ok": ok, "quote": quote})

    def prf(t, f, n):
        p = t / (t + f) if t + f else 0.0
        r = t / (t + n) if t + n else 0.0
        return p, r, (2 * p * r / (p + r) if p + r else 0.0)

    summary = {k: dict(zip(("tp", "fp", "fn", "n"), v), **dict(zip(("p", "r", "f1"), prf(*v[:3]))))
               for k, v in agg.items()}
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(json.dumps({"summary": summary, "rows": rows, "no_gold_dates": extra},
                                                   indent=2))
    L = ["# date_of_last_seizure, rules only, 200 F-S letters", "",
         "*Generated by `scripts/score_last_seizure_fs.py`. The rule was written from development letters only "
         "(EA0001-EA0160).*", "",
         "| split | letters with a gold date | right | wrong date | missed | P | R | F1 |",
         "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for k, s in summary.items():
        L.append(f"| {k} | {s['n']} | {s['tp']} | {s['fp']} | {s['fn']} | {s['p']:.3f} | {s['r']:.3f} | {s['f1']:.3f} |")
    L += ["", "| letter | split | gold | predicted | right | quote |", "|---|---|---|---|---|---|"]
    L += [f"| {r['pid']} | {r['split']} | {', '.join(r['gold'])} | {r['pred'] or ''} | {'yes' if r['ok'] else 'no'} "
          f"| {r['quote']} |" for r in rows]
    L += ["", f"Dates found in letters with no gold date ({len(extra)}):", "",
          "| letter | split | predicted | quote |", "|---|---|---|---|"]
    L += [f"| {e['pid']} | {e['split']} | {e['pred']} | {e['quote']} |" for e in extra]
    out.with_suffix(".md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:8]))


if __name__ == "__main__":
    main()
