"""Batch A D1 — apply the UMLS enrichment report to the epilepsy ontology.

Reads `.cache/umls_api/umls_enrichment_report.json` (produced by
`enrich_ontology_from_umls.py`) and writes
`rules/epilepsy_ontology_umls_overrides.py`, which the base ontology imports
at the bottom of `rules/epilepsy_ontology.py` (try/except so absence is
safe). The overrides file mutates the in-memory ConceptEntry objects at
import time to add UMLS synonyms + fill missing SCTIDs.

Reversible: delete the overrides file and re-import the ontology.

Usage: venv-medcat/bin/python scripts/apply_umls_enrichment.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REPORT_PATH = REPO_ROOT / ".cache" / "umls_api" / "umls_enrichment_report.json"
OUT_PATH = REPO_ROOT / "rules" / "epilepsy_ontology_umls_overrides.py"

if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))


def _clean(s: str) -> str:
    return s.strip()


def main() -> int:
    if not REPORT_PATH.exists():
        print(f"ERROR: {REPORT_PATH} not found. Run enrich_ontology_from_umls.py first.", file=sys.stderr)
        return 1

    report = json.loads(REPORT_PATH.read_text(encoding="utf-8"))
    if report.get("status") != "ok":
        print(f"ERROR: report status = {report.get('status')} (expected 'ok').", file=sys.stderr)
        return 2

    from rules.epilepsy_ontology import all_enum_ontologies, supplementary_ontologies
    live_ontologies = {**all_enum_ontologies(), **supplementary_ontologies()}

    enrichment = report["enrichment"]

    overrides: dict[str, dict[str, dict]] = {}
    total_syns_added = 0
    total_sctids_filled = 0
    total_entries_touched = 0

    for group_name, group_map in enrichment.items():
        live_group = live_ontologies.get(group_name)
        if not live_group:
            continue
        for value_key, patch in group_map.items():
            live_entry = live_group.get(value_key)
            if not live_entry:
                continue
            existing_syns_lc = {s.lower().strip() for s in live_entry.synonyms}
            existing_syns_lc.add((live_entry.label or "").lower().strip())
            new_syns: list[str] = []
            for cand in patch.get("candidate_synonyms", []):
                lc = _clean(cand).lower()
                if not lc or lc in existing_syns_lc:
                    continue
                # Filter out extremely long or obviously non-clinical strings.
                if len(cand) > 120:
                    continue
                new_syns.append(_clean(cand))
                existing_syns_lc.add(lc)

            set_sctid = None
            if not live_entry.sctid and patch.get("sctids"):
                # Take the shortest SCTID (most canonical) if multiple.
                sct = sorted(patch["sctids"], key=len)[0]
                if sct.isdigit():
                    set_sctid = sct

            if new_syns or set_sctid:
                entry_patch: dict = {}
                if new_syns:
                    entry_patch["add_synonyms"] = new_syns
                    total_syns_added += len(new_syns)
                if set_sctid:
                    entry_patch["set_sctid"] = set_sctid
                    total_sctids_filled += 1
                overrides.setdefault(group_name, {})[value_key] = entry_patch
                total_entries_touched += 1

    lines: list[str] = [
        '"""Auto-generated by scripts/apply_umls_enrichment.py.',
        "",
        f"Applies UMLS-Full 2025AA enrichment to the base epilepsy ontology.",
        f"Do not edit by hand — regenerate with the script.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "# Group -> value_key -> {add_synonyms: [str], set_sctid: str|None}",
        "UMLS_OVERRIDES: dict[str, dict[str, dict]] = {",
    ]
    for group_name in sorted(overrides.keys()):
        lines.append(f'    "{group_name}": {{')
        for value_key, patch in sorted(overrides[group_name].items()):
            lines.append(f'        "{value_key}": {{')
            if "add_synonyms" in patch:
                lines.append("            \"add_synonyms\": [")
                for s in patch["add_synonyms"]:
                    lines.append(f"                {json.dumps(s)},")
                lines.append("            ],")
            if "set_sctid" in patch:
                lines.append(f'            "set_sctid": {json.dumps(patch["set_sctid"])},')
            lines.append("        },")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    lines.append("PROVENANCE_TAG = \"UMLS-Full 2025AA\"")
    lines.append("")
    lines.append("def apply():")
    lines.append("    \"\"\"Mutate the imported ontology dicts in-place with UMLS enrichment.\"\"\"")
    lines.append("    from rules.epilepsy_ontology import (")
    lines.append("        all_enum_ontologies, supplementary_ontologies,")
    lines.append("    )")
    lines.append("    all_maps = {**all_enum_ontologies(), **supplementary_ontologies()}")
    lines.append("    for group_name, updates in UMLS_OVERRIDES.items():")
    lines.append("        onto = all_maps.get(group_name)")
    lines.append("        if not onto:")
    lines.append("            continue")
    lines.append("        for value_key, patch in updates.items():")
    lines.append("            entry = onto.get(value_key)")
    lines.append("            if not entry:")
    lines.append("                continue")
    lines.append("            existing = {s.lower().strip() for s in entry.synonyms}")
    lines.append("            for syn in patch.get(\"add_synonyms\", []):")
    lines.append("                if syn.lower().strip() not in existing:")
    lines.append("                    entry.synonyms.append(syn)")
    lines.append("                    existing.add(syn.lower().strip())")
    lines.append("            sct = patch.get(\"set_sctid\")")
    lines.append("            if sct and not entry.sctid:")
    lines.append("                entry.sctid = sct")
    lines.append("            if PROVENANCE_TAG not in entry.source_provenance:")
    lines.append("                entry.source_provenance.append(PROVENANCE_TAG)")

    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_PATH}")
    print(f"  Groups touched:        {len(overrides)}")
    print(f"  Entries touched:       {total_entries_touched}")
    print(f"  Synonyms added:        {total_syns_added}")
    print(f"  SCTIDs filled:         {total_sctids_filled}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
