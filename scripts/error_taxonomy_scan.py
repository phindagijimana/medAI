#!/usr/bin/env python3
"""Scan baseline (max_new_tokens=1024) manifests through the 12-category
error taxonomy from paper Table 8. Fills Table 8 with real counts.

For each (manifest, silver_module) pair, run smart-repair on the model
response, then classify each field-level disagreement into:
  missed_fact / wrong_label / negation / uncertainty / temporal /
  medication_status / eeg_semantic / mri_semantic / conflict /
  unsupported_inference / evidence_mismatch / schema

Writes:
  eval/results/error_taxonomy_summary.md
  eval/results/error_taxonomy_summary.json
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from eval.error_taxonomy import score_error_taxonomy, ALL_CATEGORIES
from schema import (
    ClinicalSeizureModule, DocumentMetadata, DocumentType,
    MedicationModule,
)
from services.smart_repair import try_smart_repair

REPO = Path(__file__).resolve().parent.parent
MANIFESTS = REPO / "data" / "run_manifests"
SILVER = REPO / "data" / "fonferko_shadrach_2024" / "silver_labels_v0_2_1"
OUT = REPO / "eval" / "results"

MODULE_CLASSES = {
    "clinical_seizure": ClinicalSeizureModule,
    "medication": MedicationModule,
}


def _load_silver():
    out = {}
    for f in SILVER.glob("EA*.json"):
        d = json.loads(f.read_text(encoding="utf-8"))
        out[d["doc_id"]] = d["phenotype"]
    return out


def main():
    silver = _load_silver()
    # per (arm, module) -> Counter of error categories
    counts = defaultdict(lambda: {c: 0 for c in ALL_CATEGORIES})
    n_docs = defaultdict(int)
    seen = defaultdict(set)

    for f in MANIFESTS.rglob("*.json"):
        try:
            m = json.loads(f.read_text(encoding="utf-8"))
        except Exception:
            continue
        pid = m.get("prompt_id", "")
        parts = pid.split(".")
        if len(parts) != 3:
            continue
        module_name, arm, version = parts
        if module_name not in MODULE_CLASSES or version != "v1":
            continue
        doc_id = m.get("source_doc_id", "")
        key = (doc_id, arm, module_name)
        if key in seen["k"]:
            continue
        seen["k"].add(key)

        n_docs[f"{arm}/{module_name}"] += 1

        # Reconstruct + smart-repair
        doc = DocumentMetadata(
            doc_id=doc_id, doc_type=DocumentType.PROGRESS_NOTE,
            doc_date=date(2024, 1, 1), patient_id=doc_id,
            icd10cm_codes=[], snomed_ct_codes=[],
        )
        module_cls = MODULE_CLASSES[module_name]
        validated, _p, _e = try_smart_repair(
            m.get("raw_response", ""), module_cls, doc,
        )

        pred_mod = validated.model_dump(mode="json") if validated else None
        gold_mod = (silver.get(doc_id) or {}).get(module_name) or None

        schema_failed = not bool(m.get("final_valid"))
        report = score_error_taxonomy(
            doc_id=doc_id, module=module_name,
            pred_module=pred_mod, gold_module=gold_mod,
            manifest_schema_failed=schema_failed,
        )
        for cat, c in report.counts.items():
            counts[f"{arm}/{module_name}"][cat] += c

    # Print + save
    OUT.mkdir(parents=True, exist_ok=True)
    out_json = {}
    for arm_key in sorted(counts):
        out_json[arm_key] = {"n_docs": n_docs[arm_key], **counts[arm_key]}

    (OUT / "error_taxonomy_summary.json").write_text(
        json.dumps(out_json, indent=2), encoding="utf-8",
    )

    # Markdown table
    md = [
        "## Table 8. Error taxonomy — 12 categories × 6 arm-module combinations (baseline max_new_tokens=1024)\n",
        "*Generated by `scripts/error_taxonomy_scan.py`. Categories per paper Table 8. Errors per document may fall in multiple categories.*\n",
        "| Category | " + " | ".join(sorted(counts.keys())) + " |",
        "|---|" + "|".join(["---:"] * len(counts)) + "|",
    ]
    for cat in ALL_CATEGORIES:
        row = [cat]
        for arm_key in sorted(counts.keys()):
            row.append(str(counts[arm_key][cat]))
        md.append("| " + " | ".join(row) + " |")
    md.append("")
    md.append("**Documents per arm/module (n):**")
    for arm_key in sorted(n_docs):
        md.append(f"- {arm_key}: {n_docs[arm_key]}")

    (OUT / "error_taxonomy_summary.md").write_text("\n".join(md) + "\n",
                                                       encoding="utf-8")

    # Console
    print(f"{'arm/module':<32} " + " ".join(f"{c[:12]:>13}" for c in ALL_CATEGORIES))
    for arm_key in sorted(counts):
        row = f"{arm_key:<32} " + " ".join(
            f"{counts[arm_key][c]:>13}" for c in ALL_CATEGORIES
        )
        print(row)
    print(f"\nwrote → {OUT / 'error_taxonomy_summary.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
