"""Phase 6b silver-labelling stub — GPT-5.6-terra on 10 MTSamples notes.

Per project memory: OpenAI is research-only in MedAI-EPI, held-out tier —
must NOT be the same tier that generated the training data. Synth-v1 was
generated by ``gpt-5.6-sol`` (see ``data/episynth_corpus/v1/run_metadata.json``)
so ``gpt-5.6-terra`` is the correct held-out labelling tier.

Reads the first N notes from
``data/eval_corpora/mtsamples_neuro/manifest.csv`` and produces
``data/eval_corpora/mtsamples_neuro/silver_gold_<n>.json`` with a v0.2.1
EpilepsyPhenotype per note.

Status
------
This is a scaffold; it only runs when both:
1. The `openai` Python package is importable from `venv-medcat`.
2. `OPENAI_API_KEY` is set in the environment.

If either check fails, the script exits 10 (PENDING) with a message and
writes NO output — silver-labelling is deferred to an operational job
the user runs offline with the correct venv/keys.

Usage
-----
    venv-medcat/bin/python scripts/silver_label_mtsamples.py [--n 10]
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CORPUS_ROOT = REPO_ROOT / "data" / "eval_corpora" / "mtsamples_neuro"


PROMPT_TEMPLATE = """You are a clinical NLP extractor. Read the neurology note
below and produce a MedAI-EPI v0.2.1 EpilepsyPhenotype JSON. Extract every
field that is documented; leave undocumented fields as {value=null,
certainty="not_documented"}. Return ONLY valid JSON with no prose.

Clinical note:
\"\"\"
{note}
\"\"\"

Phenotype JSON:
"""


def _check_prereqs() -> tuple[bool, str]:
    try:
        import openai  # noqa: F401
    except ImportError:
        return False, "openai package not installed in venv-medcat"
    if not os.environ.get("OPENAI_API_KEY"):
        return False, "OPENAI_API_KEY not set in environment"
    return True, ""


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--n", type=int, default=10)
    p.add_argument("--model", default="gpt-5.6-terra")
    args = p.parse_args(argv)

    ok, reason = _check_prereqs()
    if not ok:
        print(f"[silver] PENDING: {reason}")
        print(f"[silver] Rerun this script from an environment that has "
              f"`openai` installed and OPENAI_API_KEY set. Silver labels "
              f"will land at {CORPUS_ROOT}/silver_gold_{args.n}.json.")
        return 10

    manifest_path = CORPUS_ROOT / "manifest.csv"
    if not manifest_path.exists():
        print(f"[silver] FAIL: no manifest at {manifest_path}. Run "
              "scripts/fetch_mtsamples_neuro.py first.")
        return 2

    with manifest_path.open() as fh:
        rows = list(csv.DictReader(fh))[:args.n]
    print(f"[silver] Labelling {len(rows)} notes with {args.model}")

    from openai import OpenAI       # type: ignore
    client = OpenAI()

    labels = []
    for row in rows:
        note = (CORPUS_ROOT / row["id"] / "note.txt").read_text()
        prompt = PROMPT_TEMPLATE.format(note=note)
        # Use the responses API pattern used elsewhere in the repo
        # (`scripts/generate_synth_corpus.py`).
        resp = client.responses.create(
            model=args.model,
            input=prompt,
            temperature=0.0,
        )
        raw = resp.output_text.strip()
        # Strip potential markdown fence.
        if raw.startswith("```"):
            raw = raw.strip("`")
            if raw.startswith("json\n"):
                raw = raw[5:]
            raw = raw.rsplit("```", 1)[0].strip()
        try:
            pheno = json.loads(raw)
        except Exception as e:
            print(f"[silver] {row['id']}: JSON parse fail: {e}")
            pheno = {"raw_output": raw, "parse_error": str(e)}
        labels.append({
            "doc_id": row["id"],
            "source_url": row["source_url"],
            "silver_model": args.model,
            "labelled_at": datetime.now(timezone.utc).isoformat(),
            "phenotype": pheno,
        })
        print(f"[silver] OK {row['id']} ({len(raw)} chars raw)")

    out = CORPUS_ROOT / f"silver_gold_{args.n}.json"
    out.write_text(json.dumps(labels, indent=2))
    print(f"[silver] Wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
