#!/usr/bin/env python3
"""Emit (prompt, completion) training pairs for LoRA fine-tune from the
polished synth-v3 corpus.

Input:
    data/eval_corpora/synth_v3_polish/
        manifest.csv                   — universal manifest v1.0
        documents/{visit_id}.txt       — 493 generated notes
    data/episynth_corpus/v3_polish/
        patients/{patient_id}.json     — semantic plans
        targets/{patient_id}/target_phenotype.json   — Evidence[T] gold
        (generated by convert_synth_corpus_targets.py --corpus-version v3_polish)

Output:
    data/finetune_data/synth_v3_polish_train.jsonl  — one row per visit
    data/finetune_data/synth_v3_polish_val.jsonl    — patient-level 10% val

Row schema:
    {
      "patient_id": "P004000",
      "visit_id":   "P004000_V01",
      "note_type":  "new_patient_consult",
      "prompt":     "Extract the epilepsy phenotype ...\\n\\nClinical text:\\n\"\"\"\\n<note>\\n\"\"\"\\n\\nPhenotype JSON:\\n",
      "completion": "<v0.2.1 EpilepsyPhenotype JSON>"
    }

Usage:
    venv-medcat/bin/python scripts/emit_synth_v3_training_pairs.py \\
        --corpus-dir data/eval_corpora/synth_v3_polish \\
        --targets-dir data/episynth_corpus/v3_polish/targets \\
        --out-dir data/finetune_data \\
        --val-frac 0.10 \\
        --seed 0

Sanity check (dump 3 pairs to stdout, no file write):
    venv-medcat/bin/python scripts/emit_synth_v3_training_pairs.py \\
        --corpus-dir data/eval_corpora/synth_v3_polish \\
        --targets-dir data/episynth_corpus/v3_polish/targets \\
        --dry-run --n 3
"""

from __future__ import annotations

import argparse
import csv
import json
import random
import re
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent


PROMPT_TEMPLATE = (
    "Extract the epilepsy phenotype from this clinical text into the "
    "MedAI-EPI v0.2.1 JSON schema. Return only valid JSON.\n\n"
    "Clinical text:\n\"\"\"\n{note}\n\"\"\"\n\n"
    "Phenotype JSON:\n"
)


def _load_target(targets_dir: Path, patient_id: str) -> dict | None:
    p = targets_dir / patient_id / "target_phenotype.json"
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None


def _load_manifest(corpus_dir: Path) -> list[dict]:
    m = corpus_dir / "manifest.csv"
    if not m.exists():
        raise SystemExit(f"Missing {m}")
    with m.open() as fh:
        return list(csv.DictReader(fh))


def _emit_pair(row: dict, note_text: str, target: dict) -> dict:
    return {
        "patient_id": row["patient_id"],
        "visit_id":   row["visit_id"],
        "note_type":  row["note_type"],
        "care_setting": row.get("care_setting", ""),
        "phenotype_profile": row.get("phenotype_profile", ""),
        "prompt":     PROMPT_TEMPLATE.format(note=note_text.strip()),
        "completion": json.dumps(target, ensure_ascii=False),
    }


def _split_by_patient(pairs: list[dict], val_frac: float, seed: int) -> tuple[list[dict], list[dict]]:
    """Patient-level split so no patient's visits straddle train/val."""
    by_pid: dict[str, list[dict]] = defaultdict(list)
    for p in pairs:
        by_pid[p["patient_id"]].append(p)
    pids = sorted(by_pid.keys())
    rng = random.Random(seed)
    rng.shuffle(pids)
    n_val = max(1, int(round(len(pids) * val_frac)))
    val_pids = set(pids[:n_val])
    train, val = [], []
    for pid in pids:
        (val if pid in val_pids else train).extend(by_pid[pid])
    return train, val


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--corpus-dir", default="data/eval_corpora/synth_v3_polish")
    ap.add_argument("--targets-dir", default="data/episynth_corpus/v3_polish/targets")
    ap.add_argument("--out-dir", default="data/finetune_data")
    ap.add_argument("--val-frac", type=float, default=0.10)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--dry-run", action="store_true",
                    help="Print first --n pairs to stdout, do not write files.")
    ap.add_argument("--n", type=int, default=3,
                    help="With --dry-run, number of pairs to show.")
    args = ap.parse_args()

    corpus = REPO / args.corpus_dir if not Path(args.corpus_dir).is_absolute() else Path(args.corpus_dir)
    targets = REPO / args.targets_dir if not Path(args.targets_dir).is_absolute() else Path(args.targets_dir)
    out_dir = REPO / args.out_dir if not Path(args.out_dir).is_absolute() else Path(args.out_dir)

    manifest = _load_manifest(corpus)

    pairs: list[dict] = []
    n_missing_note = 0
    n_missing_target = 0
    n_ok = 0
    per_type: dict[str, int] = defaultdict(int)
    per_profile: dict[str, int] = defaultdict(int)

    for row in manifest:
        note_path = corpus / row["note_path"]
        if not note_path.exists():
            n_missing_note += 1
            continue
        note_text = note_path.read_text(encoding="utf-8")
        if not note_text.strip():
            n_missing_note += 1
            continue

        target = _load_target(targets, row["patient_id"])
        if target is None:
            n_missing_target += 1
            continue

        pair = _emit_pair(row, note_text, target)
        pairs.append(pair)
        n_ok += 1
        per_type[row["note_type"]] += 1
        per_profile[row.get("phenotype_profile", "unknown")] += 1

    if args.dry_run:
        print(f"[emit] dry-run — would emit {n_ok} pairs "
              f"({n_missing_note} missing note, {n_missing_target} missing target).\n")
        for pair in pairs[: args.n]:
            print("=" * 60)
            print(f"visit_id: {pair['visit_id']}  patient_id: {pair['patient_id']}  "
                  f"note_type: {pair['note_type']}  phenotype: {pair['phenotype_profile']}")
            print("--- prompt (truncated) ---")
            print(pair["prompt"][:400] + "...")
            print("--- completion (truncated) ---")
            print(pair["completion"][:400] + "...")
        return 0

    train, val = _split_by_patient(pairs, args.val_frac, args.seed)
    out_dir.mkdir(parents=True, exist_ok=True)
    train_path = out_dir / "synth_v3_polish_train.jsonl"
    val_path = out_dir / "synth_v3_polish_val.jsonl"

    with train_path.open("w") as fh:
        for p in train:
            fh.write(json.dumps(p, ensure_ascii=False) + "\n")
    with val_path.open("w") as fh:
        for p in val:
            fh.write(json.dumps(p, ensure_ascii=False) + "\n")

    print(f"[emit] Manifest rows: {len(manifest)}")
    print(f"[emit] Pairs emitted: {n_ok}")
    print(f"[emit]   missing note:   {n_missing_note}")
    print(f"[emit]   missing target: {n_missing_target}")
    print(f"[emit] Train: {len(train):4d} → {train_path}")
    print(f"[emit] Val:   {len(val):4d} → {val_path}")
    print()
    print("[emit] Note-type distribution:")
    for k, v in sorted(per_type.items(), key=lambda x: -x[1]):
        print(f"    {k:<24} {v:4d}")
    print()
    print("[emit] Phenotype-profile distribution:")
    for k, v in sorted(per_profile.items(), key=lambda x: -x[1]):
        print(f"    {k:<24} {v:4d}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
