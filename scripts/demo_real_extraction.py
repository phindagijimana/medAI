#!/usr/bin/env python3
"""End-to-end demonstration: real Med42 M1 output → long-format CSV.

Loads the actual manifests generated by SLURM job 89472 for a chosen
Fonferko-Shadrach letter (default EA0001), applies the production
smart_repair chain to the raw model response, assembles a validated
EpilepsyPhenotype, and flattens via services/tabular.to_long_rows into
the 16-column CSV promised in the paper (Supp Table S8) and the README.

The output is what a research team actually gets when they call
POST /extract/csv on this letter with arm=M1.

Writes:
    eval/results/example_extraction_<doc_id>.csv
    eval/results/example_extraction_<doc_id>.md   (rendered as a markdown table)
"""

from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from schema import (
    ClinicalSeizureModule, DocumentMetadata, DocumentType,
    EpilepsyPhenotype, MedicationModule,
)
from services.smart_repair import try_smart_repair
from services.tabular import LONG_COLUMNS, rows_to_csv_bytes, to_long_rows


MANIFESTS = REPO / "data" / "run_manifests"
SILVER = REPO / "data" / "fonferko_shadrach_2024" / "silver_labels_v0_2_1"
FS_GOLD = REPO / "data" / "fonferko_shadrach_2024" / "zenodo_8356494" / "Json"
OUT = REPO / "eval" / "results"
ARM = "M1"
DOC_ID = "EA0001"

MODULE_CLASSES = {
    "clinical_seizure": ClinicalSeizureModule,
    "medication": MedicationModule,
}


def _find_manifest(module: str, arm: str, doc_id: str) -> dict | None:
    """Locate the manifest whose prompt_id matches module.arm.v1 and whose
    source_doc_id matches doc_id."""
    for f in MANIFESTS.rglob("*.json"):
        try:
            m = json.loads(f.read_text(encoding="utf-8"))
        except Exception:
            continue
        if m.get("prompt_id") != f"{module}.{arm}.v1":
            continue
        if m.get("source_doc_id") != doc_id:
            continue
        return m
    return None


def _repair(module_name: str, manifest: dict, doc: DocumentMetadata):
    module_cls = MODULE_CLASSES[module_name]
    return try_smart_repair(manifest.get("raw_response", ""), module_cls, doc)


def main():
    silver_path = SILVER / f"{DOC_ID}.json"
    silver = json.loads(silver_path.read_text(encoding="utf-8"))
    doc_type_str = silver["doc_type"]

    doc = DocumentMetadata(
        doc_id=DOC_ID, patient_id=silver["patient_id"],
        doc_type=DocumentType(doc_type_str), doc_date=date(2024, 1, 1),
    )

    phenotype_kwargs = {"document": doc}
    print(f"=== Real Med42 M1 extraction for {DOC_ID} ({doc_type_str}) ===\n")
    for module_name in ("clinical_seizure", "medication"):
        m = _find_manifest(module_name, ARM, DOC_ID)
        if m is None:
            print(f"  {module_name}: no manifest found")
            continue
        validated, tier, err = _repair(module_name, m, doc)
        raw_valid = m.get("raw_valid", False)
        final_valid = validated is not None
        print(f"  {module_name}:")
        print(f"    manifest run_id     = {m.get('run_id','?')[:12]}…")
        print(f"    raw JSON valid      = {raw_valid}")
        print(f"    repaired valid      = {final_valid}")
        print(f"    tier used           = {tier or 'raw'}")
        print(f"    duration_s          = {m.get('duration_s',0):.2f}")
        print(f"    tokens generated    = {m.get('raw_response_tokens','?')}")
        if validated is not None:
            phenotype_kwargs[module_name] = validated

    phen = EpilepsyPhenotype(**phenotype_kwargs)
    long_rows = to_long_rows(phen, include_not_documented=False)
    n_content = sum(1 for r in long_rows if r["confidence"] != "not_documented")
    print(f"\n  Long-format rows emitted (content-only): {n_content}")

    OUT.mkdir(parents=True, exist_ok=True)
    csv_bytes = rows_to_csv_bytes(long_rows, fieldnames=LONG_COLUMNS)
    csv_path = OUT / f"example_extraction_{DOC_ID}.csv"
    csv_path.write_bytes(csv_bytes)

    md_lines = [
        f"## Real Med42-8B M1 extraction — long-format CSV output for {DOC_ID}\n",
        f"*Generated by `scripts/demo_real_extraction.py` from the actual "
        f"SLURM job 89472 manifest for letter {DOC_ID}, arm {ARM}, "
        f"schema v0.2.1, after two-tier smart_repair. {n_content} content-carrying "
        f"rows shown (not_documented rows filtered out for readability; the "
        f"canonical CSV at `{csv_path.relative_to(REPO)}` includes them).*\n",
        "| module | field | value | evidence_text | confidence |",
        "|---|---|---|---|---|",
    ]
    for r in long_rows:
        v = str(r["value"])[:80]
        e = str(r["evidence_text"])[:60]
        md_lines.append(f"| {r['module']} | {r['field']} | {v} | {e} | {r['confidence']} |")
    md_path = OUT / f"example_extraction_{DOC_ID}.md"
    md_path.write_text("\n".join(md_lines) + "\n", encoding="utf-8")

    print(f"\nwrote → {csv_path}")
    print(f"wrote → {md_path}\n")
    print(f"Preview (first 6 content rows):")
    print(f"{'module':<20} {'field':<28} {'value':<35} {'confidence':<12}")
    print("-" * 100)
    for r in long_rows[:6]:
        print(f"{r['module']:<20} {r['field']:<28} {str(r['value'])[:35]:<35} {r['confidence']:<12}")

    # -------------------------------------------------------------------
    # Correctness vs Fonferko-Shadrach native gold
    # -------------------------------------------------------------------
    gold_entities = json.loads(
        (FS_GOLD / f"{DOC_ID}.json").read_text(encoding="utf-8")
    )
    print(f"\n=== Correctness vs Fonferko-Shadrach native gold ({DOC_ID}) ===\n")

    def _gold_summary():
        out = []
        drugs, freq = [], None
        epilepsy_type_txt, seiz_type_txt = None, None
        etiology_txt = None
        for e in gold_entities:
            a = e.get("attributes", {}) or {}
            txt = (e.get("text") or "").replace("-", " ")
            if e["entity"] == "Prescription":
                drugs.append(f"{a.get('DrugName','?').lower()} "
                             f"{a.get('DrugDose','?')} {a.get('DoseUnit','?')} "
                             f"×{a.get('Frequency','?')}/day")
            elif e["entity"] == "SeizureFrequency" and freq is None:
                lo = a.get("LowerNumberOfSeizures"); hi = a.get("UpperNumberOfSeizures")
                tp = a.get("TimePeriod")
                if lo or hi:
                    freq = f"{lo}–{hi} per {tp or '?'}"
            elif e["entity"] == "Diagnosis":
                dc = a.get("DiagCategory","").lower()
                if dc == "epilepsy" and epilepsy_type_txt is None:
                    epilepsy_type_txt = txt
                elif dc in ("multipleseizures","singleseizure") and seiz_type_txt is None:
                    seiz_type_txt = txt
            elif e["entity"] == "PatientHistory" and "haemorrhage" in txt.lower():
                etiology_txt = f"{txt} ({a.get('YearDate','')})"
        return {
            "epilepsy_type": epilepsy_type_txt,
            "predominant_seizure_type": seiz_type_txt,
            "seizure_frequency": freq,
            "current_asms": drugs,
            "etiology_details": etiology_txt,
        }

    def _extracted_summary():
        med = phenotype_kwargs.get("medication")
        cs = phenotype_kwargs.get("clinical_seizure")
        d = {"epilepsy_type": None, "predominant_seizure_type": None,
              "seizure_frequency": None, "current_asms": [], "etiology_details": None}
        if med is not None:
            for ev in med.current_asms:
                v = ev.value
                if v is not None:
                    d["current_asms"].append(
                        f"{v.generic_name} {v.dose_text or ''}".strip()
                    )
        if cs is not None:
            for f_ in ("epilepsy_type", "predominant_seizure_type",
                       "seizure_frequency", "etiology_details_text"):
                ev = getattr(cs, f_, None)
                if ev is not None and ev.value is not None:
                    key = f_ if f_ != "etiology_details_text" else "etiology_details"
                    d[key] = str(ev.value)
        return d

    gs, es = _gold_summary(), _extracted_summary()
    header = f"{'Field':<28} {'F-S gold':<45} {'Extracted (M1)':<40} {'Match'}"
    print(header)
    print("-" * len(header))
    match_count = total_count = 0

    def _fmt(v):
        if v is None: return "—"
        if isinstance(v, list): return "; ".join(v) if v else "—"
        return str(v)

    def _matches(g, e):
        if g is None and (e is None or e == [] or e == ""):
            return None
        if g is None or e is None or e == [] or e == "":
            return "✗"
        g_s = _fmt(g).lower(); e_s = _fmt(e).lower()
        # lenient: any token overlap of ≥ 1 shared drug name / seizure keyword
        g_tokens = set(g_s.replace(",", " ").split())
        e_tokens = set(e_s.replace(",", " ").split())
        return "✓" if (g_tokens & e_tokens) else "✗"

    rows_out = []
    for field in ("epilepsy_type", "predominant_seizure_type",
                   "seizure_frequency", "current_asms", "etiology_details"):
        m = _matches(gs[field], es[field])
        if m is not None:
            total_count += 1
            if m == "✓":
                match_count += 1
        marker = m or "n/a"
        print(f"{field:<28} {_fmt(gs[field])[:44]:<45} "
              f"{_fmt(es[field])[:39]:<40} {marker}")
        rows_out.append({
            "field": field, "gold": _fmt(gs[field]),
            "extracted_m1": _fmt(es[field]), "match": marker,
        })

    print(f"\n  Overall on this letter: {match_count}/{total_count} in-scope "
          f"fields matched (lenient token-overlap).")
    print(f"  Consistent with §Table 4b-gold: medication content extracts; "
          f"ClinicalSeizure module is refractory to Med42-8B under M1 "
          f"(paper's central finding).")

    # append to markdown output
    md_extra = ["\n### Correctness vs F-S native gold\n",
                 f"| Field | F-S gold | Extracted (M1) | Match |",
                 "|---|---|---|:---:|"]
    for r in rows_out:
        md_extra.append(f"| {r['field']} | {r['gold']} | {r['extracted_m1']} | {r['match']} |")
    md_extra.append(f"\n**Score: {match_count}/{total_count} in-scope fields "
                     f"matched on this letter (lenient token-overlap match).**")
    with md_path.open("a", encoding="utf-8") as fh:
        fh.write("\n".join(md_extra) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
