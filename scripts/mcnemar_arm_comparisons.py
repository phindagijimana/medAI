#!/usr/bin/env python3
"""Paired McNemar's tests for content-validity across LLM arms (M0/M1/M2).

For each pair (arm_a, arm_b) and each module, count discordant pairs:
  b01 = docs where a=fail, b=pass
  b10 = docs where a=pass, b=fail

McNemar's chi-squared = (|b01 - b10| - 1)^2 / (b01 + b10)  with continuity correction.
Two-tailed p from chi-square df=1.

Writes eval/results/mcnemar_arm_comparisons.md.
"""

from __future__ import annotations

import json
import math
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from schema import (
    ClinicalSeizureModule, DocumentMetadata, DocumentType,
    MedicationModule,
)
from services.smart_repair import try_smart_repair


REPO = Path(__file__).resolve().parent.parent
MANIFESTS = REPO / "data" / "run_manifests"
OUT = REPO / "eval" / "results"

MODULE_CLASSES = {
    "clinical_seizure": ClinicalSeizureModule,
    "medication": MedicationModule,
}


def _has_content(module_dict):
    if not isinstance(module_dict, dict):
        return False
    for k, v in module_dict.items():
        if isinstance(v, dict) and v.get("value") is not None:
            return True
        if isinstance(v, list) and len(v) > 0:
            return True
    return False


def _chi2_p_two_tail_df1(chi2):
    """Two-tailed p for chi-square df=1 = 1 - erf(sqrt(chi2/2)).
    Rough closed form using math.erf (Python stdlib)."""
    if chi2 <= 0:
        return 1.0
    return 1.0 - math.erf(math.sqrt(chi2 / 2.0))


def _mcnemar(b01, b10):
    """McNemar's test with continuity correction. Return (chi2, p)."""
    n = b01 + b10
    if n == 0:
        return (0.0, 1.0)
    chi2 = (abs(b01 - b10) - 1) ** 2 / n
    p = _chi2_p_two_tail_df1(chi2)
    return (chi2, p)


def main():
    # doc_id -> module -> arm -> is_content_valid?
    outcomes = defaultdict(lambda: defaultdict(dict))
    seen = defaultdict(set)

    for f in MANIFESTS.rglob("*.json"):
        try:
            m = json.loads(f.read_text(encoding="utf-8"))
        except Exception:
            continue
        pid = m.get("prompt_id", "")
        parts = pid.split(".")
        if len(parts) != 3:
            continue
        module_name, arm, version = parts
        if module_name not in MODULE_CLASSES or version != "v1":
            continue
        doc_id = m.get("source_doc_id", "")
        key = (doc_id, arm, module_name)
        if key in seen["k"]:
            continue
        seen["k"].add(key)

        doc = DocumentMetadata(
            doc_id=doc_id, doc_type=DocumentType.PROGRESS_NOTE,
            doc_date=date(2024, 1, 1), patient_id=doc_id,
            icd10cm_codes=[], snomed_ct_codes=[],
        )
        validated, _p, _e = try_smart_repair(
            m.get("raw_response", ""), MODULE_CLASSES[module_name], doc,
        )
        d = validated.model_dump(mode="json") if validated else {}
        outcomes[doc_id][module_name][arm] = 1 if _has_content(d) else 0

    # Build paired comparisons
    pairs = [("M0", "M1"), ("M0", "M2"), ("M1", "M2")]
    rows = []
    for module in MODULE_CLASSES:
        for a, b in pairs:
            b01 = b10 = both = neither = 0
            for doc_id, mods in outcomes.items():
                if module not in mods:
                    continue
                arm_a = mods[module].get(a)
                arm_b = mods[module].get(b)
                if arm_a is None or arm_b is None:
                    continue
                if arm_a == 0 and arm_b == 1: b01 += 1
                elif arm_a == 1 and arm_b == 0: b10 += 1
                elif arm_a == 1 and arm_b == 1: both += 1
                else: neither += 1
            chi2, p = _mcnemar(b01, b10)
            rows.append({
                "module": module,
                "arm_a": a, "arm_b": b,
                "both": both, "a_only": b10, "b_only": b01,
                "neither": neither,
                "chi2": chi2, "p": p,
            })

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "mcnemar_arm_comparisons.json").write_text(
        json.dumps(rows, indent=2), encoding="utf-8",
    )

    md = [
        "## Paired McNemar's tests — content-validity across LLM arms\n",
        "*Generated by `scripts/mcnemar_arm_comparisons.py`. Continuity-corrected "
        "McNemar's chi-squared, two-tailed p from chi-square df=1.*\n",
        "| Module | Arm A | Arm B | Both valid | A-only | B-only | Neither | χ² | p |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        p_str = f"{r['p']:.3g}" if r['p'] >= 1e-4 else f"{r['p']:.2e}"
        md.append(
            f"| {r['module']} | {r['arm_a']} | {r['arm_b']} | "
            f"{r['both']} | {r['a_only']} | {r['b_only']} | {r['neither']} | "
            f"{r['chi2']:.2f} | {p_str} |"
        )
    (OUT / "mcnemar_arm_comparisons.md").write_text("\n".join(md) + "\n",
                                                       encoding="utf-8")

    print("Paired arm comparisons on content-validity:")
    print(f"{'module':<20} {'A':>3} vs {'B':>3}  {'both':>5} {'A-only':>7} {'B-only':>7}  {'chi2':>6}  {'p':>7}")
    for r in rows:
        p_str = f"{r['p']:.3g}" if r['p'] >= 1e-4 else f"{r['p']:.2e}"
        print(f"{r['module']:<20} {r['arm_a']:>3} vs {r['arm_b']:>3}  "
              f"{r['both']:>5} {r['a_only']:>7} {r['b_only']:>7}  "
              f"{r['chi2']:>6.2f}  {p_str:>7}")
    print(f"\nwrote → {OUT / 'mcnemar_arm_comparisons.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
